/** Reproducible import of licensed source PNGs. See art-source/README.md. */
import { readFileSync, writeFileSync } from 'node:fs';
import { decodePng } from './png.ts';
import { outlined, shiftY, silhouette, type Frame, type Animation } from '../src/art/types.ts';

const SIZE = 30;
const colors = new Map<string, string>();
function color(r: number, g: number, b: number): string {
  const hex = '#' + [r, g, b].map(v => v.toString(16).padStart(2, '0')).join('').toUpperCase();
  let ch = colors.get(hex);
  if (!ch) { ch = String.fromCharCode(0x100 + colors.size); colors.set(hex, ch); }
  return ch;
}
function strip(file: string, fw: number, fh: number, count: number, row = 0, grass = false): Frame[] {
  const img = decodePng(readFileSync(file));
  return Array.from({ length: count }, (_, i) => Array.from({ length: fh }, (_, y) => {
    let line = '';
    for (let x = 0; x < fw; x++) {
      const at = ((row * fh + y) * img.width + i * fw + x) * 4;
      const [r = 0, g = 0, b = 0, a = 0] = img.rgba.subarray(at, at + 4);
      line += a < 128 || (grass && g > r * 0.85 && g > b * 1.3) ? '.' : color(r, g, b);
    }
    return line;
  }));
}

/** A common crop and scale for the whole animal, never a different scale per frame. */
function fit(sets: Frame[][], flip: boolean): Frame[][] {
  let left = Infinity, top = Infinity, right = 0, bottom = 0;
  for (const frames of sets) for (const f of frames) f.forEach((row, y) => [...row].forEach((c, x) => {
    if (c !== '.') { left = Math.min(left, x); right = Math.max(right, x); top = Math.min(top, y); bottom = Math.max(bottom, y); }
  }));
  const w = right - left + 1, h = bottom - top + 1;
  const scale = Math.min((SIZE - 2) / w, (SIZE - 3) / h);
  const dw = Math.round(w * scale), dh = Math.round(h * scale);
  const ox = Math.floor((SIZE - dw) / 2), oy = SIZE - dh - 2;
  return sets.map(frames => frames.map(f => Array.from({ length: SIZE }, (_, y) => {
    let line = '';
    for (let x = 0; x < SIZE; x++) {
      const dx = x - ox, dy = y - oy;
      const sx = Math.min(w - 1, Math.floor(dx / scale));
      const sy = Math.min(h - 1, Math.floor(dy / scale));
      line += dx < 0 || dx >= dw || dy < 0 || dy >= dh ? '.' : (f[top + sy]?.[left + (flip ? w - 1 - sx : sx)] ?? '.');
    }
    return line;
  })));
}

function squash(f: Frame, ratio: number): Frame {
  return f.map((_, y) => {
    const sy = Math.floor((y - (SIZE - 2) * (1 - ratio)) / ratio);
    const source = f[sy] ?? '.'.repeat(SIZE);
    return source;
  });
}

const specs = [
  { name: 'zorro', idle: strip('art-source/scratchio/fox-idle.png', 64, 36, 6), walk: strip('art-source/scratchio/fox-walk.png', 64, 36, 8), flip: true },
  { name: 'capibara', idle: strip('art-source/charlie/charlie.png', 64, 64, 8, 1), walk: strip('art-source/charlie/charlie.png', 64, 64, 8, 8, true), flip: false },
];
const sprites = specs.map(s => {
  const [idle = [], walk = []] = fit([s.idle, s.walk], s.flip);
  const base = idle[0];
  if (!base) throw new Error(s.name);
  const pose = (f: Frame): Frame => outlined(f);
  const crouch = squash(base, 0.82);
  // Added poses: body compression on charge, head recoil on cry, low resting body on death.
  let headTop = SIZE, headRight = 0;
  base.forEach((row, y) => [...row].forEach((c, x) => {
    if (c !== '.' && x >= SIZE * 0.65 && y < SIZE * 0.7) { headTop = Math.min(headTop, y); headRight = Math.max(headRight, x); }
  }));
  const ex = headRight - 3, ey = headTop + 4;
  const blink = base.map((row, y) => y === ey ? [...row].map((c, x) => x >= ex && x <= ex + 1 && c !== '.' ? 'd' : c).join('') : row);
  const rest = squash(blink, 0.5);
  const cry = base.map((row, y) => y === headTop + 7 ? [...row].map((c, x) => x >= headRight - 2 && c !== '.' ? 'R' : c).join('') : row);
  const animations: Record<string, Animation> = {
    quieto: { fps: 6, frames: idle.map(pose) },
    trotar: { fps: s.name === 'zorro' ? 12 : 10, frames: walk.map(pose) },
    parpadeo: { fps: 8, frames: [pose(blink)], loop: false },
    cargar: { fps: 10, frames: [pose(crouch), pose(shiftY(crouch, -1))] },
    ladrar: { fps: 10, frames: [pose(shiftY(base, -1)), pose(cry), pose(base)], loop: false },
    dano: { fps: 8, frames: [pose(shiftY(base, 1))], loop: false },
    muerte: { fps: 6, frames: [pose(base), pose(crouch), pose(rest), pose(shiftY(rest, 1))], loop: false },
    dormir: { fps: 1.5, frames: [pose(rest), pose(shiftY(rest, 1))] },
    estirar: { fps: 6, frames: [pose(rest), pose(crouch), pose(shiftY(base, -1)), pose(base)], loop: false },
    silueta: { fps: 1, frames: [silhouette(pose(base), 'K')] },
  };
  return { name: s.name, group: 'personajes', width: 32, height: 32, anchor: { x: 0.5, y: 29 / 32 }, flash: true, animations };
});
writeFileSync('src/art/sprites/faunaImported.ts', '// Generated by scripts/import-fauna.ts from licensed PNGs. Do not edit.\nimport type { SpriteDef } from "../types.ts";\nexport const importedFauna: readonly SpriteDef[] = ' + JSON.stringify(sprites, null, 2) + ';\n');
writeFileSync('src/art/faunaPalette.ts', '// Generated by scripts/import-fauna.ts. Original asset colors.\nexport const FAUNA_PALETTE = ' + JSON.stringify([...colors].map(([hex, char], i) => ({ char, hex, name: `Fauna ${i + 1}`, use: 'Arte externo con licencia' })), null, 2) + ';\n');
console.warn(`Imported ${sprites.length} animals with their complete animation sets.`);
