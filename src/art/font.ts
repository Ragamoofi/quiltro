export const GLYPH_HEIGHT = 5;

/** Text as rows of palette characters (no outline), 1 px between glyphs. */
export function textRows(text: string, color: string): Frame {
  const glyphs = [...text.toUpperCase()].map((ch) => GLYPHS[ch] ?? GLYPHS['?'] ?? []);
  const rows: string[] = [];
  for (let y = 0; y < GLYPH_HEIGHT; y++) {
    rows.push(glyphs.map((g) => (g[y] ?? '').replace(/#/g, color)).join('.'));
  }
  return rows;
}

/** Text with a 1 px ink outline (7 px tall). */
export function outlinedText(text: string, color: string, ink = 'k'): Frame {
  return outlined(textRows(text, color), ink);
}
